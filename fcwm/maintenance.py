"""Einrichten und Aufräumen: `fcwm init` und `fcwm cleanup`."""
from __future__ import annotations

import logging
import subprocess
from pathlib import Path

from . import config as config_mod
from . import titlebar
from .backends import get_backend
from .monitors import Monitor, detect_monitors

log = logging.getLogger("fcwm")

# alle KWin-Skripte, die das Tool dauerhaft lädt
PLUGINS = ("fcwm_listener", "fcwm_separators", "fcwm_previews",
           "evewm_listener", "evewm_separators", "evewm_previews")   # inkl. früherem Namen


def _aliases(n: int) -> list[str]:
    if n == 1:
        return ["main"]
    if n == 2:
        return ["left", "right"]
    if n == 3:
        return ["left", "center", "right"]
    return [f"m{i + 1}" for i in range(n)]


def _monitors() -> list[Monitor]:
    try:
        mons = get_backend("auto").screens()   # KWin liefert zusätzlich den Arbeitsbereich
    except Exception:  # noqa: BLE001 – Fallback kscreen/xrandr
        mons = None
    return mons or detect_monitors()


def render_config(monitors: list[Monitor], language: str) -> str:
    """Startkonfiguration: jeder Monitor als 2x2-Raster (Hochkant 1x2), ein Profil, das alle füllt."""
    mons = sorted(monitors, key=lambda m: (m.geometry.x, m.geometry.y))
    aliases = _aliases(len(mons))
    lines = [
        "# FleetCommander – generated by `fcwm init`",
        "# Everything here can also be edited in the web UI (fcwm web -> http://127.0.0.1:8765/).",
        "",
        "settings:",
        "  backend: auto",
        f"  language: {language}",
        "  match:",
        "    caption_regex: '^EVE - (?P<char>.+)$'",
        "    resource_class: '^steam_app_8500$'   # Steam/Proton; leave empty for other launchers",
        "",
        "monitors:",
    ]
    for alias, m in zip(aliases, mons):
        g = m.geometry
        grid = "1x2" if g.h > g.w else "2x2"
        lines += [f"  {alias}:",
                  f"    output: {m.name}            # {g.w}x{g.h} at {g.x},{g.y}",
                  f"    grid: {grid}",
                  "    reserve: auto          # leave room for panels/taskbars"]
    lines += [
        "",
        "default_profile: Default",
        "",
        "profiles:",
        "  Default:",
        "    description: All clients fill all monitors – assign characters in the web UI",
        f"    fill: [{', '.join(aliases)}]",
        "",
    ]
    return "\n".join(lines)


def init(path: str | None, force: bool, language: str) -> Path:
    target = Path(path).expanduser() if path else config_mod.DEFAULT_PATHS[0]
    if target.exists() and not force:
        raise FileExistsError(str(target))
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render_config(_monitors(), language), encoding="utf-8")
    return target


def _busctl(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["busctl", "--user", "call", *args], capture_output=True, text=True)


def service_active() -> bool:
    r = subprocess.run(["systemctl", "--user", "is-active", "fcwm.service"], capture_output=True, text=True)
    return r.stdout.strip() == "active"


def cleanup() -> dict[str, int]:
    """Entfernt alles, was das Tool in der KDE-Sitzung hinterlässt: geladene KWin-Skripte,
    globale Kurzbefehle, eigene Fensterregeln und Farbschemata. Die Konfiguration bleibt."""
    unloaded = 0
    for plugin in PLUGINS:
        r = _busctl("org.kde.KWin", "/Scripting", "org.kde.kwin.Scripting", "unloadScript", "s", plugin)
        unloaded += r.stdout.strip().endswith("true")
    names = _busctl("org.kde.KWin", "/component/kwin", "org.kde.kglobalaccel.Component", "shortcutNames").stdout
    shortcuts = 0
    for name in {n for n in names.split('"') if n.startswith(("fcwm-", "evewm-"))}:
        r = _busctl("org.kde.kglobalaccel", "/kglobalaccel", "org.kde.KGlobalAccel", "unregister", "ss", "kwin", name)
        shortcuts += r.stdout.strip().endswith("true")
    rules = titlebar.remove_rules()
    if rules:
        _busctl("org.kde.KWin", "/KWin", "org.kde.KWin", "reconfigure")
    return {"scripts": unloaded, "shortcuts": shortcuts, "rules": rules}


def _listening(port: int) -> bool:
    import socket
    with socket.socket() as s:
        s.settimeout(0.3)
        return s.connect_ex(("127.0.0.1", port)) == 0


def open_ui(port: int = 8765, config_path: str | None = None) -> str:
    """Web-UI im Browser öffnen; läuft fcwm noch nicht, zuerst starten (Dienst, sonst im Hintergrund)."""
    import shutil
    import sys
    import time
    url = f"http://127.0.0.1:{port}/"
    if not _listening(port):
        has_unit = subprocess.run(["systemctl", "--user", "cat", "fcwm.service"],
                                  capture_output=True).returncode == 0
        if not (has_unit and port == 8765 and config_path is None
                and subprocess.run(["systemctl", "--user", "start", "fcwm.service"]).returncode == 0):
            cmd = [sys.executable, "-m", "fcwm"] + (["-c", config_path] if config_path else []) + \
                  ["web", "--port", str(port)]
            log_dir = Path.home() / ".cache" / "fcwm"
            log_dir.mkdir(parents=True, exist_ok=True)
            with open(log_dir / "web.log", "ab") as out:
                subprocess.Popen(cmd, stdout=out, stderr=out, stdin=subprocess.DEVNULL, start_new_session=True)
        for _ in range(40):
            if _listening(port):
                break
            time.sleep(0.2)
        else:
            raise RuntimeError(f"fcwm did not start on port {port} – see ~/.cache/fcwm/web.log")
    if shutil.which("xdg-open"):
        subprocess.Popen(["xdg-open", url], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                         start_new_session=True)
    return url


def _post(port: int, path: str) -> dict:
    import json
    import urllib.request
    req = urllib.request.Request(f"http://127.0.0.1:{port}{path}", data=b"{}", method="POST",
                                 headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=15) as r:
        return json.loads(r.read() or b"{}")


def reload_config(port: int = 8765) -> str:
    """Die laufende Instanz liest ihre Konfiguration neu ein (ohne Fenster zu bewegen)."""
    if not _listening(port):
        raise RuntimeError("not_running")
    return _post(port, "/api/reload").get("config", "")


def restart(port: int = 8765) -> str:
    """Laufende Instanz neu starten – als Dienst über systemd, sonst startet sie sich selbst neu."""
    import time
    if service_active() and port == 8765:
        if subprocess.run(["systemctl", "--user", "restart", "fcwm.service"]).returncode != 0:
            raise RuntimeError("systemctl --user restart fcwm failed")
        how = "service"
    elif _listening(port):
        _post(port, "/api/restart")
        how = "process"
        time.sleep(0.5)          # alte Instanz gibt den Port frei
    else:
        raise RuntimeError("not_running")
    for _ in range(50):
        if _listening(port):
            return how
        time.sleep(0.2)
    raise RuntimeError(f"fcwm did not come back on port {port} – check `journalctl --user -u fcwm` "
                       "or ~/.cache/fcwm/web.log")
